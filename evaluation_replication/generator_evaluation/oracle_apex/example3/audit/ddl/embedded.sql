CREATE TABLE EBADEMODGCUSTOMERS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_ADDRESS VARCHAR2(100) NOT NULL,
    FULL_NAME VARCHAR2(100) NOT NULL
);

CREATE TABLE EBADEMODGDEPT (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DNAME VARCHAR2(100) NOT NULL,
    LOC VARCHAR2(100) NOT NULL
);

CREATE TABLE EBADEMODGPRODUCTS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IMAGE_CHARSET VARCHAR2(100) NOT NULL,
    IMAGE_FILENAME VARCHAR2(100) NOT NULL,
    IMAGE_LAST_UPDATED DATE NOT NULL,
    IMAGE_MIME_TYPE VARCHAR2(100) NOT NULL,
    PRODUCT_NAME VARCHAR2(100) NOT NULL,
    UNIT_PRICE NUMBER NOT NULL
);

CREATE TABLE EBADEMODGORDERS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_DATETIME TIMESTAMP NOT NULL,
    ORDER_STATUS VARCHAR2(100) NOT NULL,
    ebademodgcustomers_id NUMBER NOT NULL,
    FOREIGN KEY (ebademodgcustomers_id) REFERENCES EbaDemoDgCustomers(id)
);

CREATE TABLE EBADEMODGEMP (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMM NUMBER NOT NULL,
    ENAME VARCHAR2(100) NOT NULL,
    HIREDATE DATE NOT NULL,
    JOB VARCHAR2(100) NOT NULL,
    SAL NUMBER NOT NULL,
    ebademodgdept_id NUMBER NOT NULL,
    ebademodgemp_mgr_id NUMBER NOT NULL,
    FOREIGN KEY (ebademodgdept_id) REFERENCES EbaDemoDgDept(id),
    FOREIGN KEY (ebademodgemp_mgr_id) REFERENCES EbaDemoDgEmp(id)
);

CREATE TABLE EBADEMODGORDERITEMS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LINE_ITEM_ID NUMBER NOT NULL,
    QUANTITY NUMBER NOT NULL,
    UNIT_PRICE NUMBER NOT NULL,
    ebademodgproducts_id NUMBER NOT NULL,
    ebademodgorders_id NUMBER NOT NULL,
    FOREIGN KEY (ebademodgproducts_id) REFERENCES EbaDemoDgProducts(id),
    FOREIGN KEY (ebademodgorders_id) REFERENCES EbaDemoDgOrders(id)
);


