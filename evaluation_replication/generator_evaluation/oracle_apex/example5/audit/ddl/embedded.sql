CREATE TABLE EBADEMODADEPT (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEPTNO NUMBER NOT NULL,
    DNAME VARCHAR2(100) NOT NULL,
    LOC VARCHAR2(100) NOT NULL
);

CREATE TABLE EBADEMODAEMP (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMM NUMBER NOT NULL,
    EMPNO NUMBER NOT NULL,
    ENAME VARCHAR2(100) NOT NULL,
    HIREDATE DATE NOT NULL,
    JOB VARCHAR2(100) NOT NULL,
    SAL NUMBER NOT NULL,
    ebademodadept_id NUMBER NOT NULL,
    ebademodaemp_mgr_id NUMBER NOT NULL,
    FOREIGN KEY (ebademodadept_id) REFERENCES EbaDemoDaDept(id),
    FOREIGN KEY (ebademodaemp_mgr_id) REFERENCES EbaDemoDaEmp(id)
);


