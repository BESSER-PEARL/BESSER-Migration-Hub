CREATE TABLE EBADEMOTREEDEPT (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEPTNO NUMBER NOT NULL,
    DNAME VARCHAR2(100) NOT NULL,
    LOC VARCHAR2(100) NOT NULL
);

CREATE TABLE EBADEMOTREEEMP (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMM NUMBER NOT NULL,
    DEPTNO NUMBER NOT NULL,
    EMPNO NUMBER NOT NULL,
    ENAME VARCHAR2(100) NOT NULL,
    HIREDATE DATE NOT NULL,
    JOB VARCHAR2(100) NOT NULL,
    SAL NUMBER NOT NULL,
    ebademotreeemp_mgr_id NUMBER NOT NULL,
    FOREIGN KEY (ebademotreeemp_mgr_id) REFERENCES EbaDemoTreeEmp(id)
);

CREATE TABLE EBADEMOTREEPOPULATION (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CREATED TIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(100) NOT NULL,
    POPULATION NUMBER NOT NULL,
    REGION NUMBER NOT NULL,
    ROW_VERSION_NUMBER NUMBER NOT NULL,
    STATE_CODE VARCHAR2(100) NOT NULL,
    STATE_NAME VARCHAR2(100) NOT NULL,
    UPDATED TIMESTAMP NOT NULL,
    UPDATED_BY VARCHAR2(100) NOT NULL
);

