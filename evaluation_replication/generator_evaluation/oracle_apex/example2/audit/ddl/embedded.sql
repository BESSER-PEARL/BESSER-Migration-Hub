CREATE TABLE EBADEMOLOADDEPT (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEPTNO NUMBER NOT NULL,
    DNAME VARCHAR2(100) NOT NULL,
    LOC VARCHAR2(100) NOT NULL
);

CREATE TABLE EBADEMOLOADSALES (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COUNTRY VARCHAR2(100) NOT NULL,
    CREATED DATE NOT NULL,
    ITEM_TYPE VARCHAR2(100) NOT NULL,
    LAST_UPDATED DATE NOT NULL,
    ORDER_DATE DATE NOT NULL,
    ORDER_ID NUMBER NOT NULL,
    ORDER_PRIORITY VARCHAR2(100) NOT NULL,
    REGION VARCHAR2(100) NOT NULL,
    SALES_CHANNEL VARCHAR2(100) NOT NULL,
    SHIP_DATE DATE NOT NULL,
    TOTAL_COST NUMBER NOT NULL,
    TOTAL_PROFIT NUMBER NOT NULL,
    TOTAL_REVENUE NUMBER NOT NULL,
    UNIT_COST NUMBER NOT NULL,
    UNIT_PRICE NUMBER NOT NULL,
    UNITS_SOLD NUMBER NOT NULL
);

CREATE TABLE EBADEMOLOADEMP (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMM NUMBER NOT NULL,
    CREATED DATE NOT NULL,
    EMPNO NUMBER NOT NULL,
    ENAME VARCHAR2(100) NOT NULL,
    HIREDATE DATE NOT NULL,
    JOB VARCHAR2(100) NOT NULL,
    LAST_UPDATED DATE NOT NULL,
    SAL NUMBER NOT NULL,
    ebademoloaddept_id NUMBER NOT NULL,
    ebademoloademp_mgr_id NUMBER NOT NULL,
    FOREIGN KEY (ebademoloaddept_id) REFERENCES EbaDemoLoadDept(id),
    FOREIGN KEY (ebademoloademp_mgr_id) REFERENCES EbaDemoLoadEmp(id)
);


