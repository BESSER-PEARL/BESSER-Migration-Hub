--------------------------------------------------
-- SAFE DROP
--------------------------------------------------

BEGIN
    -- Step 1: drop all FK constraints on target tables
    --         (handles stale constraint names from previous imports)
    FOR c IN (
        SELECT constraint_name, table_name
        FROM   user_constraints
        WHERE  table_name IN ('EBADEMOCALSESSIONS', 'EBADEMOCALPROJECTS', 'EBADEMOCALMYSESSIONS')
        AND    constraint_type = 'R'
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || c.table_name
                || ' DROP CONSTRAINT ' || c.constraint_name;
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;

    -- Step 2: drop views that share a name with a target table
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoCalSessions'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoCalProjects'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoCalMysessions'; EXCEPTION WHEN OTHERS THEN NULL; END;

    -- Step 3: drop tables
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoCalSessions CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoCalProjects CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoCalMysessions CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
/

