--------------------------------------------------
-- SAFE DROP
--------------------------------------------------

BEGIN
    -- Step 1: drop all FK constraints on target tables
    --         (handles stale constraint names from previous imports)
    FOR c IN (
        SELECT constraint_name, table_name
        FROM   user_constraints
        WHERE  table_name IN ('EBADEMOIREMP', 'EBADEMOIRDEPT')
        AND    constraint_type = 'R'
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || c.table_name
                || ' DROP CONSTRAINT ' || c.constraint_name;
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;

    -- Step 2: drop views that share a name with a target table
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoIrEmp'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoIrDept'; EXCEPTION WHEN OTHERS THEN NULL; END;

    -- Step 3: drop tables
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoIrEmp CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoIrDept CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
/

--------------------------------------------------
-- TABLES
--------------------------------------------------

-- EbaDemoIrDept
CREATE TABLE EbaDemoIrDept (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deptno NUMBER NOT NULL,
    dname VARCHAR2(100) NOT NULL,
    loc VARCHAR2(100) NOT NULL
);

-- EbaDemoIrEmp
CREATE TABLE EbaDemoIrEmp (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comm NUMBER NOT NULL,
    deptno NUMBER NOT NULL,
    empno NUMBER NOT NULL,
    ename VARCHAR2(100) NOT NULL,
    hiredate DATE NOT NULL,
    job VARCHAR2(100) NOT NULL,
    sal NUMBER NOT NULL,
    ebademoiremp_mgr_id NUMBER NOT NULL,
    FOREIGN KEY (ebademoiremp_mgr_id) REFERENCES EbaDemoIrEmp(id)
);
