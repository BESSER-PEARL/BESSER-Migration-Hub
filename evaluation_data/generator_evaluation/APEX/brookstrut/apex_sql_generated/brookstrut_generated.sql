--------------------------------------------------
-- SAFE DROP
--------------------------------------------------

BEGIN
    -- Step 1: drop all FK constraints on target tables
    --         (handles stale constraint names from previous imports)
    FOR c IN (
        SELECT constraint_name, table_name
        FROM   user_constraints
        WHERE  table_name IN ('OOWDEMOSALESHISTORY', 'OOWDEMOSTOREPRODUCTS', 'OOWDEMOSTORES', 'OOWDEMOREGIONS', 'OOWDEMOITEMS')
        AND    constraint_type = 'R'
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || c.table_name
                || ' DROP CONSTRAINT ' || c.constraint_name;
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;

    -- Step 2: drop views that share a name with a target table
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW OowDemoSalesHistory'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW OowDemoStoreProducts'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW OowDemoStores'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW OowDemoRegions'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW OowDemoItems'; EXCEPTION WHEN OTHERS THEN NULL; END;

    -- Step 3: drop tables
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE OowDemoSalesHistory CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE OowDemoStoreProducts CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE OowDemoStores CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE OowDemoRegions CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE OowDemoItems CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
/

--------------------------------------------------
-- TABLES
--------------------------------------------------

-- OowDemoItems
CREATE TABLE OowDemoItems (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id NUMBER NOT NULL,
    item_desc VARCHAR2(100) NOT NULL,
    item_name VARCHAR2(100) NOT NULL,
    item_type VARCHAR2(100) NOT NULL,
    msrp NUMBER NOT NULL
);

-- OowDemoRegions
CREATE TABLE OowDemoRegions (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id NUMBER NOT NULL,
    is_default_yn VARCHAR2(100) NOT NULL,
    region_color VARCHAR2(100) NOT NULL,
    region_lat NUMBER NOT NULL,
    region_lng NUMBER NOT NULL,
    region_name VARCHAR2(100) NOT NULL,
    region_zoom VARCHAR2(100) NOT NULL
);

-- OowDemoStores
CREATE TABLE OowDemoStores (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id NUMBER NOT NULL,
    store_address VARCHAR2(100) NOT NULL,
    store_city VARCHAR2(100) NOT NULL,
    store_lat NUMBER NOT NULL,
    store_lng NUMBER NOT NULL,
    store_name VARCHAR2(100) NOT NULL,
    store_state VARCHAR2(100) NOT NULL,
    store_type VARCHAR2(100) NOT NULL,
    store_zip VARCHAR2(100) NOT NULL,
    oowdemoregions_id NUMBER NOT NULL,
    FOREIGN KEY (oowdemoregions_id) REFERENCES OowDemoRegions(id)
);

-- OowDemoStoreProducts
CREATE TABLE OowDemoStoreProducts (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discount_pct NUMBER NOT NULL,
    id NUMBER NOT NULL,
    item_price NUMBER NOT NULL,
    sale_end_date DATE NOT NULL,
    sale_start_date DATE NOT NULL,
    oowdemoitems_id NUMBER NOT NULL,
    oowdemostores_id NUMBER NOT NULL,
    FOREIGN KEY (oowdemoitems_id) REFERENCES OowDemoItems(id),
    FOREIGN KEY (oowdemostores_id) REFERENCES OowDemoStores(id)
);

-- OowDemoSalesHistory
CREATE TABLE OowDemoSalesHistory (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_of_sale DATE NOT NULL,
    id NUMBER NOT NULL,
    item_price NUMBER NOT NULL,
    quantity NUMBER NOT NULL,
    transaction_id VARCHAR2(100) NOT NULL,
    oowdemostores_id NUMBER NOT NULL,
    oowdemostoreproducts_id NUMBER NOT NULL,
    FOREIGN KEY (oowdemostores_id) REFERENCES OowDemoStores(id),
    FOREIGN KEY (oowdemostoreproducts_id) REFERENCES OowDemoStoreProducts(id)
);
