--------------------------------------------------
-- SAFE DROP
--------------------------------------------------

BEGIN
    -- Step 1: drop all FK constraints on target tables
    --         (handles stale constraint names from previous imports)
    FOR c IN (
        SELECT constraint_name, table_name
        FROM   user_constraints
        WHERE  table_name IN ('EBADEMOIGEMP', 'EBADEMOIGPEOPLE', 'EBADEMOIGDEPT')
        AND    constraint_type = 'R'
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || c.table_name
                || ' DROP CONSTRAINT ' || c.constraint_name;
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;

    -- Step 2: drop views that share a name with a target table
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoIgEmp'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoIgPeople'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW EbaDemoIgDept'; EXCEPTION WHEN OTHERS THEN NULL; END;

    -- Step 3: drop tables
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoIgEmp CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoIgPeople CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE EbaDemoIgDept CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
/

