--------------------------------------------------
-- SAFE DROP
--------------------------------------------------

BEGIN
    -- Step 1: drop all FK constraints on target tables
    --         (handles stale constraint names from previous imports)
    FOR c IN (
        SELECT constraint_name, table_name
        FROM   user_constraints
        WHERE  table_name IN ('PAYMENT', 'LINEITEM', 'ORDER_HEADER', 'ACCOUNT', 'SHOPPINGCART', 'CUSTOMER', 'WEBUSER', 'PRODUCT')
        AND    constraint_type = 'R'
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || c.table_name
                || ' DROP CONSTRAINT ' || c.constraint_name;
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;

    -- Step 2: drop views that share a name with a target table
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW Payment'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW LineItem'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW order_header'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW Account'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW ShoppingCart'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW Customer'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW WebUser'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW Product'; EXCEPTION WHEN OTHERS THEN NULL; END;

    -- Step 3: drop tables
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE Payment CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE LineItem CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE order_header CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE Account CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE ShoppingCart CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE Customer CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE WebUser CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE Product CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
/

--------------------------------------------------
-- TABLES
--------------------------------------------------

-- Product
CREATE TABLE Product (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier VARCHAR2(100) NOT NULL,
    name VARCHAR2(100) NOT NULL
);

-- WebUser
CREATE TABLE WebUser (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR2(100) NOT NULL,
    password VARCHAR2(100) NOT NULL,
    state VARCHAR2(20) NOT NULL,
    CONSTRAINT chk_webuser_state CHECK (state IN ('Active', 'Banned', 'Blocked', 'New'))
);

-- Customer
CREATE TABLE Customer (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR2(100) NOT NULL,
    customer_id VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL,
    phone VARCHAR2(100) NOT NULL,
    webuser_id NUMBER NOT NULL,
    FOREIGN KEY (webuser_id) REFERENCES WebUser(id),
    CONSTRAINT uq_customer_webuser_id UNIQUE (webuser_id)
);

-- ShoppingCart
CREATE TABLE ShoppingCart (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created DATE NOT NULL,
    webuser_id NUMBER NOT NULL,
    FOREIGN KEY (webuser_id) REFERENCES WebUser(id),
    CONSTRAINT uq_shoppingcart_webuser_id UNIQUE (webuser_id)
);

-- Account
CREATE TABLE Account (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id VARCHAR2(100) NOT NULL,
    billing_address VARCHAR2(100) NOT NULL,
    closed_date DATE NOT NULL,
    is_closed NUMBER(1) DEFAULT 0 NOT NULL,
    open_date DATE NOT NULL,
    customer_id NUMBER NOT NULL,
    shoppingcart_id NUMBER NOT NULL,
    CONSTRAINT chk_account_is_closed CHECK (is_closed IN (0, 1)),
    FOREIGN KEY (customer_id) REFERENCES Customer(id),
    CONSTRAINT uq_account_customer_id UNIQUE (customer_id),
    FOREIGN KEY (shoppingcart_id) REFERENCES ShoppingCart(id),
    CONSTRAINT uq_account_shoppingcart_id UNIQUE (shoppingcart_id)
);

-- Order
CREATE TABLE order_header (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR2(100) NOT NULL,
    ordered_date DATE NOT NULL,
    ship_to VARCHAR2(100) NOT NULL,
    shipped_date DATE NOT NULL,
    status VARCHAR2(20) NOT NULL,
    total NUMBER NOT NULL,
    account_id NUMBER NOT NULL,
    CONSTRAINT chk_order_header_status CHECK (status IN ('Closed', 'Delivered', 'Hold', 'New', 'Shipped')),
    FOREIGN KEY (account_id) REFERENCES Account(id)
);

-- LineItem
CREATE TABLE LineItem (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price NUMBER NOT NULL,
    quantity NUMBER NOT NULL,
    order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    shoppingcart_id NUMBER NOT NULL,
    FOREIGN KEY (order_id) REFERENCES order_header(id),
    FOREIGN KEY (product_id) REFERENCES Product(id),
    FOREIGN KEY (shoppingcart_id) REFERENCES ShoppingCart(id)
);

-- Payment
CREATE TABLE Payment (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    details VARCHAR2(100) NOT NULL,
    paid_date DATE NOT NULL,
    payment_id VARCHAR2(100) NOT NULL,
    total NUMBER NOT NULL,
    account_id NUMBER NOT NULL,
    order_id NUMBER NOT NULL,
    FOREIGN KEY (account_id) REFERENCES Account(id),
    FOREIGN KEY (order_id) REFERENCES order_header(id)
);
