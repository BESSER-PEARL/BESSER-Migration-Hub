--------------------------------------------------
-- TABLES
--------------------------------------------------

-- Author
CREATE TABLE Author (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biography VARCHAR2(100) NOT NULL,
    birth_date DATE NOT NULL,
    name VARCHAR2(100) NOT NULL
);

-- Book
CREATE TABLE Book (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn VARCHAR2(100) NOT NULL,
    language VARCHAR2(20) NOT NULL,
    name VARCHAR2(100) NOT NULL,
    overview VARCHAR2(100) NOT NULL,
    publisher VARCHAR2(100) NOT NULL,
    publisher_date DATE NOT NULL,
    subject VARCHAR2(100) NOT NULL,
    CONSTRAINT chk_book_language CHECK (language IN ('English', 'French', 'German', 'Italian', 'Spanish'))
);

-- Library
CREATE TABLE Library (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR2(100) NOT NULL,
    name VARCHAR2(100) NOT NULL
);

-- Patron
CREATE TABLE Patron (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR2(100) NOT NULL,
    name VARCHAR2(100) NOT NULL
);

-- Catalog
CREATE TABLE Catalog (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id NUMBER NOT NULL,
    FOREIGN KEY (library_id) REFERENCES Library(id),
    CONSTRAINT uq_catalog_library_id UNIQUE (library_id)
);

-- Librarian
CREATE TABLE Librarian (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR2(100) NOT NULL,
    name VARCHAR2(100) NOT NULL,
    position VARCHAR2(100) NOT NULL,
    library_id NUMBER NOT NULL,
    FOREIGN KEY (library_id) REFERENCES Library(id)
);

-- Account
CREATE TABLE Account (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_value NUMBER NOT NULL,
    opened DATE NOT NULL,
    state VARCHAR2(20) NOT NULL,
    patron_id NUMBER NOT NULL,
    library_id NUMBER NOT NULL,
    CONSTRAINT chk_account_state CHECK (state IN ('Active', 'Closed', 'Frozen')),
    FOREIGN KEY (patron_id) REFERENCES Patron(id),
    CONSTRAINT uq_account_patron_id UNIQUE (patron_id),
    FOREIGN KEY (library_id) REFERENCES Library(id)
);

-- BookItem
CREATE TABLE BookItem (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode VARCHAR2(100) NOT NULL,
    borrowed DATE NOT NULL,
    due_date DATE NOT NULL,
    format VARCHAR2(20) NOT NULL,
    is_overdue NUMBER(1) DEFAULT 0 NOT NULL,
    is_refernce_only NUMBER(1) DEFAULT 0 NOT NULL,
    loan_period NUMBER NOT NULL,
    pages NUMBER NOT NULL,
    tag VARCHAR2(100) NOT NULL,
    title VARCHAR2(100) NOT NULL,
    book_id NUMBER NOT NULL,
    account_id NUMBER NOT NULL,
    library_id NUMBER NOT NULL,
    catalog_id NUMBER NOT NULL,
    FOREIGN KEY (book_id) REFERENCES Book(id),
    CONSTRAINT chk_bookitem_format CHECK (format IN ('AudioCD', 'Audiobook', 'Hardcover', 'MP3CD', 'PDF', 'PaperBack')),
    CONSTRAINT chk_bookitem_is_overdue CHECK (is_overdue IN (0, 1)),
    CONSTRAINT chk_bookitem_is_refernce_only CHECK (is_refernce_only IN (0, 1)),
    FOREIGN KEY (account_id) REFERENCES Account(id),
    FOREIGN KEY (library_id) REFERENCES Library(id),
    FOREIGN KEY (catalog_id) REFERENCES Catalog(id)
);

--------------------------------------------------
-- JUNCTION TABLES (N:M associations)
--------------------------------------------------

CREATE TABLE Author_Book (
    author_id NUMBER NOT NULL,
    book_id NUMBER NOT NULL,
    PRIMARY KEY (author_id, book_id),
    FOREIGN KEY (author_id) REFERENCES Author(id),
    FOREIGN KEY (book_id) REFERENCES Book(id)
);
