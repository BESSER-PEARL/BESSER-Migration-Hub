--------------------------------------------------
-- TABLES
--------------------------------------------------

-- Hospital
CREATE TABLE Hospital (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR2(100) NOT NULL,
    name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(100) NOT NULL
);

-- Person
CREATE TABLE Person (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    birth_date DATE NOT NULL,
    family_name VARCHAR2(100) NOT NULL,
    gender VARCHAR2(20) NOT NULL,
    given_name VARCHAR2(100) NOT NULL,
    middle_name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(100) NOT NULL,
    CONSTRAINT chk_person_gender CHECK (gender IN ('Female', 'Male', 'Other'))
);

-- Department
CREATE TABLE Department (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id NUMBER NOT NULL,
    FOREIGN KEY (hospital_id) REFERENCES Hospital(id)
);

-- Patient
CREATE TABLE Patient (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accepted_date DATE NOT NULL,
    allergies VARCHAR2(100) NOT NULL,
    patient_id VARCHAR2(100) NOT NULL,
    sickness VARCHAR2(100) NOT NULL,
    special_reqs VARCHAR2(100) NOT NULL,
    person_id NUMBER NOT NULL,
    FOREIGN KEY (person_id) REFERENCES Person(id)
);

-- Staff
CREATE TABLE Staff (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language VARCHAR2(100) NOT NULL,
    certification VARCHAR2(100) NOT NULL,
    education VARCHAR2(100) NOT NULL,
    joined DATE NOT NULL,
    person_id NUMBER NOT NULL,
    department_id NUMBER NOT NULL,
    FOREIGN KEY (person_id) REFERENCES Person(id),
    FOREIGN KEY (department_id) REFERENCES Department(id)
);

-- AdministrativeStaff
CREATE TABLE AdministrativeStaff (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id NUMBER NOT NULL,
    FOREIGN KEY (staff_id) REFERENCES Staff(id)
);

-- OperationsStaff
CREATE TABLE OperationsStaff (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id NUMBER NOT NULL,
    FOREIGN KEY (staff_id) REFERENCES Staff(id)
);

-- TechnicalStaff
CREATE TABLE TechnicalStaff (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id NUMBER NOT NULL,
    FOREIGN KEY (staff_id) REFERENCES Staff(id)
);

-- Doctor
CREATE TABLE Doctor (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location VARCHAR2(100) NOT NULL,
    speciality VARCHAR2(100) NOT NULL,
    operationsstaff_id NUMBER NOT NULL,
    FOREIGN KEY (operationsstaff_id) REFERENCES OperationsStaff(id)
);

-- Nurse
CREATE TABLE Nurse (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operationsstaff_id NUMBER NOT NULL,
    FOREIGN KEY (operationsstaff_id) REFERENCES OperationsStaff(id)
);

-- Surgeon
CREATE TABLE Surgeon (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id NUMBER NOT NULL,
    FOREIGN KEY (doctor_id) REFERENCES Doctor(id)
);

--------------------------------------------------
-- JUNCTION TABLES (N:M associations)
--------------------------------------------------

CREATE TABLE Hospital_Person (
    hospital_id NUMBER NOT NULL,
    person_id NUMBER NOT NULL,
    PRIMARY KEY (hospital_id, person_id),
    FOREIGN KEY (hospital_id) REFERENCES Hospital(id),
    FOREIGN KEY (person_id) REFERENCES Person(id)
);

CREATE TABLE OperationsStaff_Patient (
    operations_staff_id NUMBER NOT NULL,
    patient_id NUMBER NOT NULL,
    PRIMARY KEY (operations_staff_id, patient_id),
    FOREIGN KEY (operations_staff_id) REFERENCES OperationsStaff(id),
    FOREIGN KEY (patient_id) REFERENCES Patient(id)
);
